import queue
import threading
import json
import re
import time
from pathlib import Path

BASE = Path(__file__).parent
مجلد_الوحدات = BASE / 'modules'

# ═══ 1. الأنبوب (Queue) ═══
# سعته 10 فقط (كما لو كان أنبوب ماء لا يتسع لأكثر من 10 لترات في اللحظة)
الأنبوب = queue.Queue(maxsize=10) 

# ═══ 2. العمال (الوكلاء المستهلكون) ═══
def عامل_مستهلك(رقم_العامل):
    while True:
        # سحب الماء (المهمة) من الأنبوب. إذا كان الأنبوب فارغاً، ينتظر.
        مهمة = الأنبوب.get()
        
        if مهمة is None:
            # إشارة التوقف (سم للخروج)
            break
            
        سؤال, رقم_المهمة = مهمة
        try:
            # تنفيذ المهمة (بحث في البيانات)
            كلمات_البحث = set(re.findall(r'[\u0600-\u06FFa-zA-Z_]{2,}', سؤال.lower()))
            نتائج = []
            for ملف_json in مجلد_الوحدات.rglob('*.json'):
                try:
                    بيانات = json.load(open(ملف_json, encoding='utf-8'))
                    if isinstance(بيانات, dict):
                        for قسم, محتوى in بيانات.items():
                            if isinstance(محتوى, dict) and 'النصوص' in محتوى:
                                for نص in محتوى['النصوص']:
                                    نقاط = sum(1 for كلمة in كلمات_البحث if كلمة in نص.lower())
                                    if نقاط > 0:
                                        نتائج.append((نقاط, ملف_json.name, نص))
                except: pass
            
            if نتائج:
                results_sorted = sorted(نتائج, key=lambda x: -x[0])
                print(f"\n  ✅ [عامل {رقم_العامل}] أنجز المهمة {رقم_المهمة}: وجد {len(نتائج)} نتيجة.")
                print(f"     أفضل نتيجة: {results_sorted[0][2][:150]}...")
        except Exception as e:
            print(f"\n  ❌ [عامل {رقم_العامل}] فشل في المهمة {رقم_المهمة}: {e}")
        
        # إعلام الأنبوب بأن هذه المهمة انتهت (ماء خرج من الطرف الآخر)
        الأنبوب.task_done()

# ═══ 3. الواجهة (المضخة) ═══
if __name__ == '__main__':
    print("="*60)
    print(" 🚰 المحرك الأنبوبي v32.0 — المؤسس: مهدي معور")
    print(" 🎯 الماء يدخل من الأعلى، ويتحرك في الأنبوب، ويخرج من الأسفل.")
    print("="*60)
    
    # تشغيل 3 عمال (وكلاء) مستهلكين في الخلفية
    عدد_العمال = 3
    for i in range(عدد_العمال):
        t = threading.Thread(target=عامل_مستهلك, args=(i+1,), daemon=True)
        t.start()
    
    print(f"👷 تم تشغيل {عدد_العمال} وكلاء (عمال) على خط الإنتاج.")
    print(f"💧 سعة الأنبوب: 10 مهام (إذا امتلأ، سيتوقف الضخ حتى يفرغ).")
    
    رقم_المهمة = 1
    while True:
        try:
            سؤال = input("\n  أدخل السؤال (سأضخه في الأنبوب): ").strip()
            if سؤال in ('خروج', 'q', 'exit'): break
            if not سؤال: continue
            
            print(f"⏳ جاري ضخ المهمة رقم {رقم_المهمة} في الأنبوب...")
            # محاولة وضع المهمة في الأنبوب
            # إذا كان الأنبوب ممتلئاً (10 مهام)، سيتم حظر الكود هنا (Block) حتى يخرج وكيل
            الأنبوب.put((سؤال, رقم_المهمة))
            رقم_المهمة += 1
            
        except (EOFError, KeyboardInterrupt): break

    # إيقاف العمال
    print("\n⏳ في انتظار إنهاء المهام المتبقية في الأنبوب...")
    الأنبوب.join() # انتظر حتى يفرغ الأنبوب تماماً
    for _ in range(عدد_العمال):
        الأنبوب.put(None) # إعطاء إشارة التوقف لكل عامل
    print("✅ تم إغلاق الأنبوب بنجاح.")
